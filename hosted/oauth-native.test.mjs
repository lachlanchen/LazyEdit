import test from 'node:test';
import assert from 'node:assert/strict';
import {generateKeyPairSync, sign} from 'node:crypto';
import {mkdtempSync, writeFileSync, rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {Registry} from './store.mjs';
import {createOAuth, challengeFor} from './oauth.mjs';
import {secret} from '../studio/auth.mjs';

test('native Apple signup, proof binding, isolation, revocation and rollback', async t => {
  const dir = mkdtempSync(join(tmpdir(), 'studio-native-apple-'));
  const registry = new Registry(join(dir, 'registry.sqlite'), 'edit.test', 20);
  t.after(() => {registry.db.close(); rmSync(dir, {recursive: true, force: true});});
  const appleKey = generateKeyPairSync('ec', {namedCurve: 'P-256'});
  writeFileSync(join(dir, 'apple-key'), appleKey.privateKey.export({type: 'pkcs8', format: 'pem'}));
  const keys = generateKeyPairSync('rsa', {modulusLength: 2048});
  const jwk = {...keys.publicKey.export({format: 'jwk'}), kid: 'fixture', alg: 'RS256'};
  let nonce, subject = 'apple-person', audience = 'art.test.native', refresh = true, exchanges = 0, revoked;
  const config = {encryptionKey: 'a'.repeat(64), apple: {enabled: true, clientId: 'art.test.web', nativeClientId: 'art.test.native', keyId: 'TEST', teamId: 'TEAM', privateKeyFile: join(dir, 'apple-key')}};
  const oauth = createOAuth(registry, config, 'https://edit.test', async (url, options) => {
    if (url.endsWith('/keys')) return Response.json({keys: [jwk]});
    const values = options.body;
    assert.equal(values.get('client_id'), 'art.test.native');
    const clientClaims = JSON.parse(Buffer.from(values.get('client_secret').split('.')[1], 'base64url'));
    assert.equal(clientClaims.sub, 'art.test.native');
    if (url.endsWith('/revoke')) {revoked = values.get('token'); return new Response('');}
    exchanges++;
    assert.equal(values.has('redirect_uri'), false);
    const now = Math.floor(Date.now()/1000), enc = value => Buffer.from(JSON.stringify(value)).toString('base64url');
    const input = enc({alg: 'RS256', kid: 'fixture'}) + '.' + enc({iss: 'https://appleid.apple.com', sub: subject, aud: audience, nonce, iat: now, exp: now+300, email: 'not-link-proof@example.test'});
    return Response.json({id_token: input + '.' + sign('RSA-SHA256', Buffer.from(input), keys.privateKey).toString('base64url'), ...(refresh ? {refresh_token: 'private-native-refresh'} : {})});
  });
  function start(owner) {
    const verifier = secret(), flow = oauth.startApple({challenge: challengeFor(verifier)}, owner, secret());
    nonce = flow.nonce;
    return {state: flow.state, verifier, code: 'one-time-test-code'};
  }
  const password = 'a-test-password-for-recovery';
  const registration = {username: 'alice', password, invitation: registry.invite()};
  const first = start();
  await assert.rejects(oauth.finishApple({...first, verifier: secret(), registration}, secret()), {status: 401});
  assert.equal(exchanges, 0, 'wrong device proof never exchanges a provider code');
  const {ticket} = await oauth.finishApple({...first, registration}, secret());
  const owner = oauth.redeem({ticket, verifier: first.verifier});
  assert.equal(registry.login('alice', password, secret()), owner, 'invited account has a usable recovery/deletion password');
  assert.ok(registry.workspace(owner));
  assert.equal(registry.isAdmin(owner), false);
  await assert.rejects(oauth.finishApple(first, secret()), {status: 401});
  assert.throws(() => oauth.redeem({ticket, verifier: first.verifier}), {status: 401});
  const again = start();
  const next = await oauth.finishApple(again, secret());
  assert.equal(oauth.redeem({...next, verifier: again.verifier}), owner, 'same subject reuses account without invitation');
  const bob = registry.addOwner('bob', password);
  await assert.rejects(oauth.finishApple(start(bob), secret()), {status: 409}, 'subject collision never overwrites a link');
  subject = 'different-person';
  await assert.rejects(oauth.finishApple(start(owner), secret()), {status: 409}, 'owner cannot silently switch Apple identity');
  const waiting = start();
  const enrollment = await oauth.finishApple(waiting, secret());
  assert.equal(enrollment.registrationRequired, true);
  assert.equal(registry.db.prepare('SELECT count(*) AS n FROM users').get().n, 2, 'verified Apple alone cannot create an uninvited account');
  assert.throws(() => oauth.enrollApple({...enrollment, verifier: secret()}, secret()), {status: 401});
  const signup = {username: 'enrolled', password, invitation: registry.invite()};
  assert.throws(() => oauth.enrollApple({...enrollment, verifier: waiting.verifier, registration: {...signup, invitation: 'bad'}}, secret()), {status: 400});
  const enrollResult = oauth.enrollApple({...enrollment, verifier: waiting.verifier, registration: signup}, secret());
  assert.equal(oauth.redeem({...enrollResult, verifier: waiting.verifier}), registry.login('enrolled', password, secret()));
  assert.throws(() => oauth.enrollApple({...enrollment, verifier: waiting.verifier, registration: signup}, secret()), {status: 401});
  subject = 'third-person';
  await assert.rejects(oauth.finishApple({...start(), registration: {username: 'alice', password, invitation: registry.invite()}}, secret()), {status: 409}, 'a matching username never links an existing account');
  await assert.rejects(oauth.finishApple({...start(), registration: {username: 'invalidinvite', password, invitation: 'invalid'}}, secret()), {status: 400});
  assert.equal(registry.db.prepare('SELECT 1 FROM users WHERE username=?').get('invalidinvite'), undefined);
  const rollback = {username: 'newuser', password, invitation: registry.invite()};
  refresh = false;
  await assert.rejects(oauth.finishApple({...start(), registration: rollback}, secret()), {status: 502});
  assert.equal(registry.db.prepare('SELECT 1 FROM users WHERE username=?').get('newuser'), undefined);
  assert.equal(registry.db.prepare('SELECT used FROM invitations WHERE used=0').get().used, 0);
  refresh = true;
  const retry = start();
  await oauth.finishApple({...retry, registration: rollback}, secret());
  assert.ok(registry.db.prepare('SELECT 1 FROM users WHERE username=?').get('newuser'));
  audience = 'art.test.web';
  await assert.rejects(oauth.finishApple(start(), secret()), {status: 401}, 'native flow cannot accept web audience');
  audience = 'art.test.native';
  const mismatch = start(); nonce = secret();
  await assert.rejects(oauth.finishApple(mismatch, secret()), {status: 401});
  const expired = start();
  registry.db.prepare('UPDATE oauth_flows SET expires=0').run();
  const beforeExpiry = exchanges;
  await assert.rejects(oauth.finishApple(expired, secret()), {status: 401});
  assert.equal(exchanges, beforeExpiry);
  subject = 'apple-person';
  const late = start(); registry.closeAccount(owner);
  await assert.rejects(oauth.finishApple(late, secret()), {status: 403});
  await oauth.unlink(owner, 'apple');
  assert.equal(revoked, 'private-native-refresh');
  assert.deepEqual(oauth.links(owner), []);
  assert.equal(oauth.failureLocation({oauthTarget: 'native', status: 403}), 'art.lazying.lazyedit://auth?oauth_error=unlinked');
});
